export function contextNote(c: { code: string; full_name: string | null; registration_complete: boolean }) {
  return c.registration_complete
    ? `العميل الحالي مسجّل: ${c.full_name ?? ""} — رقم العميل ${c.code}.`
    : `العميل الحالي غير مسجّل بعد (رقمه المؤقت ${c.code}). لا تطلب تسجيله إلا إذا أراد بدء طلب.`;
}
